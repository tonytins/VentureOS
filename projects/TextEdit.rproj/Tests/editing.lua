-- TextEdit: opening, editing, naming, and saving text files.

test.case("Opens no window until asked for one", function(app)
  test.equal(app:windows(), 0)
  test.expect(app:newWindow())
  test.equal(app:title(), "Untitled")
  test.equal(app:text("text"), "")
  test.equal(app:focused(), "text")
end)

test.case("Opens a file with its line breaks tidied", function(app)
  app:write("/mnt/user/todo.txt", "milk\r\neggs\r\n")
  test.expect(app:open("/mnt/user/todo.txt"))
  test.equal(app:text("text"), "milk\neggs\n")
  test.equal(app:text("path"), "/mnt/user/todo.txt")
  test.equal(app:title(), "todo.txt")
  test.equal(app:text("status"), "Opened todo.txt.")
end)

test.case("Marks edits and saves", function(app)
  app:write("/mnt/user/todo.txt", "milk\neggs\n")
  app:open("/mnt/user/todo.txt")
  app:type("text", "milk\neggs\nbread\n")
  test.equal(app:title(), "todo.txt (edited)")

  app:press("save")
  test.equal(app:read("/mnt/user/todo.txt"), "milk\neggs\nbread\n")
  test.equal(app:title(), "todo.txt")
  test.equal(app:text("status"), "Saved todo.txt.")
end)

test.case("Names a new file in the title bar, then saves it", function(app)
  app:newWindow()
  app:type("text", "hello")
  app:press("saveItem")
  test.equal(app:text("status"), "Type a path in the title bar, then Save.")

  app:submit("path", "/mnt/user/hello.txt")
  test.equal(app:text("status"), "A new file: Save creates hello.txt.")
  app:press("save")
  test.equal(app:read("/mnt/user/hello.txt"), "hello")
end)

test.case("Enter in the title bar opens an existing file", function(app)
  app:write("/mnt/user/todo.txt", "milk\neggs\n")
  app:newWindow()
  app:submit("path", "/mnt/user/todo.txt")
  test.equal(app:text("text"), "milk\neggs\n")
end)

test.case("Refuses a file too large to edit", function(app)
  app:write("/mnt/user/big.txt", string.rep("a", 65537))
  app:newWindow()
  app:open("/mnt/user/big.txt")
  test.equal(app:text("status"), "big.txt is too large to edit here.")
  test.equal(app:text("text"), "")
end)
